namespace Oxira.Events.Application.Features.Chat;

/// <summary>The assistant's instructions (ported from the n8n "Oxira Events" workflow).</summary>
public static class Prompts
{
    private static readonly Dictionary<string, string> LangNames = new()
    { ["ar"] = "العربية", ["en"] = "English", ["de"] = "Deutsch", ["fr"] = "Français", ["ru"] = "Русский" };

    public static string System(DateTimeOffset nowRiyadh, string lang) => Template
        .Replace("{NOW}", nowRiyadh.ToString("yyyy-MM-dd HH:mm"))
        .Replace("{LANG}", LangNames.GetValueOrDefault(lang, "العربية"));

    private const string Template = """
